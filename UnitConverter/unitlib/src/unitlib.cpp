double C2F(double x) {
    double result = x * 1.8 + 32;
    return result;
}
double F2C(double x) {
    double result = (x - 32) * 5 / 9;
    return result;
}
double Ft2M(double x) {
    double result = x * 0.3048;
    return result;
}
double M2Ft(double x) {
    double result = x * 3.28084;
    return result;
}
double Lb2Kg(double x) {
    double result = x * 0.4536;
    return result;
}
double Kg2Lb(double x) {
    double result = x * 2.2046;
    return result;
}